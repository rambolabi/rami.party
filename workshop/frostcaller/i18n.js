let LANG = 'en';

/** Translate a key. Falls back to English, then to the key itself. */
function t(key) {
    const table = STRINGS[LANG] || STRINGS.en;
    return table[key] !== undefined ? table[key] : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key);
}

/** Translate a piece of content, or hand back the English it was given. */
function tc(key, fallback) {
    const table = CONTENT[LANG];
    if (table && table[key] !== undefined) return table[key];
    return fallback;
}

/**
 * Translate, then fill in {placeholders} from an object.
 * Values are inserted as plain text by the caller, never as markup.
 */
function tv(key, vars) {
    return String(t(key)).replace(/\{(\w+)\}/g, (whole, name) =>
        (vars && vars[name] !== undefined ? String(vars[name]) : whole));
}

function setLang(id) {
    LANG = STRINGS[id] ? id : 'en';
    document.documentElement.lang = LANG;
    applyStaticStrings();

    /* The chapters really are English-only. Say so where it matters, and only
       to the people it affects. */
    const note = document.getElementById('langNote');
    if (note) note.hidden = LANG === 'en';
}

/** Fill every element carrying a data-i18n attribute. */
function applyStaticStrings() {
    document.querySelectorAll('[data-i18n]').forEach(node => {
        const key = node.dataset.i18n;
        const value = t(key);
        if (node.dataset.i18nHtml === 'true') {
            /* The only markup allowed here is <b>, and it comes from this file. */
            node.textContent = '';
            value.split(/(<b>[^<]*<\/b>)/).forEach(part => {
                if (!part) return;
                if (part.startsWith('<b>')) {
                    const b = document.createElement('strong');
                    b.textContent = part.slice(3, -4);
                    node.appendChild(b);
                } else {
                    node.appendChild(document.createTextNode(part));
                }
            });
        } else {
            node.textContent = value;
        }
    });
    /* Strings that want a link, `code` or bold go through the audited inline
       renderer in app.js rather than a second markup path of their own. */
    document.querySelectorAll('[data-i18n-rich]').forEach(node => {
        if (typeof rich !== 'function') return;
        node.textContent = '';
        rich(node, t(node.dataset.i18nRich));
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(node => {
        node.placeholder = t(node.dataset.i18nPh);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(node => {
        node.title = t(node.dataset.i18nTitle);
    });
}
