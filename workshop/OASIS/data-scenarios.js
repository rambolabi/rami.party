/* ==========================================================================
   O.A.S.I.S. — data-scenarios.js
   --------------------------------------------------------------------------
   Playbooks. One per situation, each answering the same three questions:

       BEFORE   what you do while nothing is wrong. This is where survival is
                actually decided; almost nobody does it.
       DURING   what you do in the hours and days it is happening.
       AFTER    what you do once it stops — which is when a large share of the
                injuries and deaths actually occur.

   Schema
     id       stable, deep-linked as #/play/<id> — never rename
     band     grouping id, see OASIS_BANDS below
     title, glyph, lede
     horizon  how long this situation typically runs
     before[] during[] after[]   ordered actions, **bold** supported
     facts[]  [label, value] numbers worth finding in one glance
     dont[]   the things that get people killed
     sources[] keys into OASIS_SOURCES — every playbook is traceable
     keys     extra search terms not present in the prose

   Editing rule: no folklore. If a claim cannot be traced to one of the bodies
   in OASIS_SOURCES, it does not go in.
   ========================================================================== */

